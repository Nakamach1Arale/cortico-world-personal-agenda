import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import client from '../shared/webui.js';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const allowed=['cortico-world-personal-agenda-local'];
const packages=fs.readdirSync(root,{withFileTypes:true}).filter(e=>e.isDirectory()&&e.name.startsWith('cortico-world-')).map(e=>e.name).sort();
assert.deepEqual(packages,allowed,'The publication must contain only the approved agenda package.');
assert.deepEqual(Object.keys(client.panels),['agenda'],'The publication must expose only the agenda page.');
const pkgDir=path.join(root,'cortico-world-personal-agenda-local');
const pkg=JSON.parse(fs.readFileSync(path.join(pkgDir,'package.json'),'utf8'));
assert.equal(pkg.name,'cortico-world-personal-agenda');
assert.equal(pkg.cortico?.kind,'world');
assert.equal(pkg.cortico?.api,6);
assert.equal(pkg.cortico?.describe,'describe.json');
assert.equal(pkg.cortico?.icon,'window/icon.png');
assert.ok(Array.isArray(pkg.files)&&pkg.files.includes('describe.json')&&pkg.files.includes('CHANGELOG.md'),'describe.json and CHANGELOG.md must be listed in package.json files.');
const describe=JSON.parse(fs.readFileSync(path.join(pkgDir,'describe.json'),'utf8'));
assert.ok(Array.isArray(describe.tools)&&Array.isArray(describe.events)&&Array.isArray(describe.prompts),'describe.json must export tools, events, and prompts.');
console.log('Release scope verified: personal agenda only.');
